"""Second pass: find the arXiv preprint behind a journal paper that has none.

Why this exists
---------------
The first pass (fetch_summaries.py) got every arXiv preprint and every DOI for
which Crossref publishes an abstract — 205 of 399. Everything still missing is
a journal or conference paper: IEEE, Elsevier, Springer and the CVPR/ECCV
proceedings do not hand abstracts to Crossref, so there is nothing to fetch by
DOI. Many of those papers, however, *were* posted on arXiv first.

So this pass searches arXiv by title and takes a hit only when the title
matches. The gate is the same one the project uses when resolving a DOI
(≥0.90 token similarity after normalisation): an abstract attached to the wrong
paper is worse than no abstract at all, because it looks authoritative.

Rate limiting: arXiv asks for ~3 s between requests. Every query sleeps first,
and results are cached, so a re-run does not re-hit the API.
"""
from __future__ import annotations

import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fetch_summaries import (  # noqa: E402
    CACHE, OUT, ROOT, ARXIV, ARXIV_GAP, MAX_CHARS, condense, log,
    read_papers,
)

GATE = 0.90                 # same threshold the DOI resolver uses
SEARCH = ARXIV + "?search_query=%s&start=0&max_results=5"
UA = "awesome-computed-tomography/1.0 (summary fetcher; +https://computedtomography.org/)"


def norm(s):
    return set(re.sub(r"[^a-z0-9 ]", " ", (s or "").lower()).split())


def sim(a, b):
    A, B = norm(a), norm(b)
    if not A or not B:
        return 0.0
    return len(A & B) / len(A | B)


def get(url, timeout=45):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    opener = urllib.request.build_opener(
        urllib.request.ProxyHandler(urllib.request.getproxies()))
    with opener.open(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


ENTRY = re.compile(
    r"<entry>.*?<id>http[s]?://arxiv\.org/abs/([^<]+)</id>"
    r".*?<title[^>]*>(.*?)</title>"
    r".*?<summary[^>]*>(.*?)</summary>", re.S)


def search_by_title(title):
    """Best-matching abstract on arXiv, or None if nothing clears the gate."""
    q = urllib.parse.quote('ti:"%s"' % title.replace('"', ""))
    time.sleep(ARXIV_GAP)
    try:
        body = get(SEARCH % q)
    except Exception as e:                          # noqa: BLE001
        log("  search failed: %s" % e)
        return None
    best, best_s = None, 0.0
    for m in ENTRY.finditer(body):
        got = " ".join(re.sub(r"\s+", " ", m.group(2)).split())
        s = sim(title, got)
        if s > best_s:
            best_s, best = s, " ".join(m.group(3).split())
    if best and best_s >= GATE:
        return best, best_s
    return None


def main():
    papers = read_papers()
    have = {}
    if os.path.exists(OUT):
        have = yaml.safe_load(open(OUT, encoding="utf-8")) or {}
    titles = {}
    for p in yaml.safe_load(
            open(os.path.join(ROOT, "data", "papers.yaml"), encoding="utf-8")):
        titles[p["id"]] = p.get("title", "")

    cache = {}
    if os.path.exists(CACHE):
        cache = json.load(open(CACHE, encoding="utf-8"))
    abstracts = cache.get("abstracts", {})

    missing = [p for p in papers if p["id"] not in have]
    log("missing: %d" % len(missing))
    found, failed, rejected = 0, 0, []

    for n, p in enumerate(missing, 1):
        if p["id"] in abstracts:                  # already fetched, re-derive
            found += 1
            continue
        title = titles.get(p["id"], "")
        if not title:
            failed += 1
            continue
        hit = search_by_title(title)
        if hit:
            abstracts[p["id"]] = hit[0]
            found += 1
        else:
            failed += 1
        if n % 25 == 0:
            log("  %d/%d (found %d)" % (n, len(missing), found))
            json.dump({"abstracts": abstracts},
                      open(CACHE, "w", encoding="utf-8"), ensure_ascii=False)

    json.dump({"abstracts": abstracts},
              open(CACHE, "w", encoding="utf-8"), ensure_ascii=False)

    out = dict(have)
    for p in papers:
        if p["id"] in out:
            continue
        raw = abstracts.get(p["arxiv"]) or abstracts.get(p["id"])
        if raw:
            txt = condense(raw)
            if txt:
                out[p["id"]] = txt
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# One-paragraph \"what is this paper\" blurbs, keyed by paper id.\n")
        f.write("# Generated by scripts/oneoff/fetch_summaries.py (+ a by-title\n")
        f.write("# second pass) from the arXiv and Crossref APIs. Every blurb is built\n")
        f.write("# from **verbatim sentences** of the official abstract, so it can be\n")
        f.write("# incomplete but never invented. Safe to hand-edit.\n\n")
        for k in sorted(out):
            f.write("%s: >-\n  %s\n" % (k, out[k]))
    log("total summaries: %d" % len(out))
    log("still missing: %d" % (len(papers) - len(out)))
    if rejected:
        log("rejected as below the %.2f title gate: %s" % (GATE, rejected[:10]))


if __name__ == "__main__":
    main()
